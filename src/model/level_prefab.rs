pub fn level_to_wall_rows(level: &[Vec<char>]) -> Vec<Vec<Wall>> {
    level
        .iter()
        .enumerate()
        .map(|(y, row)| {
            row.iter()
                .enumerate()
                .filter(|&(_, &chr)| chr == WALL_CHAR)
                .map(|(x, _)| Wall { x: x as u64, y: y as u64 })
                .collect()
        })
        .collect()
}

pub fn prefab_to_walls(level: Vec<Vec<char>>) -> Result<(Vec<Wall>, GridSize), ProgramError> {
    let height = level.len();
    let width = level.first().map_or(0, |row| row.len());

    if level.iter().any(|row| row.len() != width) {
        return Err(ProgramError::InconsistentLevelWidth);
    }

    let walls = level_to_wall_rows(&level).into_iter().flatten().collect();

    Ok((walls, GridSize { width: width as u64, height: height as u64 }))
}
